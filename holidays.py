from typing import Optional

def get_holiday_name(target_date: date) -> Optional[str]:
    """祝日名を取得（祝日でない場合はNone）"""
    return ALL_HOLIDAYS.get(target_date)


def is_sunday_or_holiday(target_date: date) -> bool:
    """日曜日または祝日かどうか（日祝休日判定）"""
    if target_date.weekday() == 6:  # 6=日曜日
        return True
    return target_date in ALL_HOLIDAYS
